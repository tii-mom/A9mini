function generateCandles(target, pattern) {
  return Array.from({ length: 12 }, (_, i) => {
    const status = pattern[i] ?? 'pending';
    let price = null;
    if (status === 'hit') {
      const bump = 1.015 + ((i * 7) % 9) * 0.012;
      price = +(target * bump).toFixed(4);
    } else if (status === 'miss') {
      const dip = 0.92 + ((i * 5) % 6) * 0.01;
      price = +(target * dip).toFixed(4);
    }
    const hourStr = `${String(i).padStart(2, '0')}:00 UTC`;
    return { index: i + 1, hour: hourStr, status, price };
  });
}

